// Generates src/styles/tokens.css from Kimberley's brand/colour/tokens.md and brand/type/tokens.md.
// Empty rows fall back to the provisional DESIGN.md values, each marked /* provisional */.
// Never edit tokens.css by hand: run `npm run tokens`.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";

const PROVISIONAL_COLOUR = {
  bg: "#ffffff",
  "bg-alt": "#fafafa",
  surface: "#f4f4f5",
  text: "#000000",
  muted: "#52525b",
  dim: "#a1a1aa",
  border: "#e4e4e7",
  "border-strong": "#d4d4d8",
  accent: "#ff5d1f",
  "accent-hover": "#e64a0e",
  "accent-soft": "#ffead9",
  "accent-ink": "#b83a0b",
};
const PROVISIONAL_TYPE = {
  display: 'var(--font-newsreader), "Iowan Old Style", Georgia, serif',
  heading: 'var(--font-geist-sans), "Helvetica Neue", Arial, sans-serif',
  body: 'var(--font-geist-sans), "Helvetica Neue", Arial, sans-serif',
  mono: 'var(--font-geist-mono), ui-monospace, Menlo, monospace',
};

// Shapes, depth and motion from brand/guidelines/pika-brand-guidelines-v1.md (UI shapes and depth, Motion).
const SHAPE = [
  "  --r-card: 16px;",
  "  --r-lg: 22px;",
  "  --r-input: 12px;",
  "  --r-button: 14px;",
  "  --r-small: 8px;",
  "  --r-pill: 999px;",
  "  --shadow: 0 4px 20px rgba(10, 10, 10, 0.06);",
  "  --ease-out: cubic-bezier(0.22, 1, 0.36, 1);",
  "  --spring: cubic-bezier(0.34, 1.36, 0.64, 1);",
  "  --t-ui: 200ms;",
  "  --t-card: 380ms;",
];

function rows(file) {
  if (!existsSync(file)) return [];
  return readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => l.trim().startsWith("|") && !/^\|\s*-/.test(l.trim()))
    .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()))
    .slice(1);
}

const colour = { ...PROVISIONAL_COLOUR };
const fromBrand = new Set();
for (const [token, hex] of rows("brand/colour/tokens.md")) {
  const key = token.toLowerCase().replace(/\s+/g, "-");
  if (/^#[0-9a-f]{3,8}$/i.test(hex)) {
    colour[key] = hex;
    fromBrand.add(`c:${key}`);
  }
}
const type = { ...PROVISIONAL_TYPE };
for (const [role, font] of rows("brand/type/tokens.md")) {
  const key = role.toLowerCase().split(/\s|\(/)[0];
  if (font && key in type) {
    // Google fonts are loaded with next/font in app/layout.tsx and exposed as --font-<name>.
    type[key] = `var(--font-${font.toLowerCase().replace(/\s+/g, "-")}), "${font}", "Helvetica Neue", Arial, sans-serif`;
    fromBrand.add(`t:${key}`);
  }
}

const mark = (k) => (fromBrand.has(k) ? "" : " /* provisional */");
const css = [
  "/* Generated by scripts/tokens.mjs from brand/. Do not edit by hand. */",
  ":root {",
  ...Object.entries(colour).map(([k, v]) => `  --${k}: ${v};${mark(`c:${k}`)}`),
  ...Object.entries(type).map(([k, v]) => `  --font-${k}: ${v};${mark(`t:${k}`)}`),
  ...SHAPE,
  "}",
  "",
].join("\n");

mkdirSync("src/styles", { recursive: true });
writeFileSync("src/styles/tokens.css", css);
console.log(`tokens.css written (${fromBrand.size} values from brand/, the rest provisional)`);
